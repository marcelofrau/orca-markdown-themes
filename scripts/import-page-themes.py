"""Regenerate editor/page-themes.ts and the page theme picker in orca-plugin.json.

Usage: python -I scripts/import-page-themes.py

Reads Tinta's built-in themes from themes/tinta/*.css (copies of github.com/oipoistar/tinta
resources/themes, MIT) as they are, and builds the classic themes in themes/classic.json with the
same design: Tinta's variables and rules, filled with each theme's own palette and fonts.
"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
FONT = '"Segoe UI", sans-serif'
HEADING_FONT = '"Segoe UI Variable Display", "Segoe UI", sans-serif'
CODE_FONT = '"Cascadia Code", "Cascadia Mono", "Consolas", monospace'
TOKENS = ["keyword", "string", "comment", "number", "function", "class-name", "control"]
# Tinta's callout tints, light and dark
ALERTS = {
    False: ["rgba(9, 105, 218, 0.07)", "rgba(26, 127, 55, 0.07)", "rgba(130, 80, 223, 0.07)", "rgba(154, 103, 0, 0.07)", "rgba(207, 34, 46, 0.07)"],
    True: ["rgba(68, 147, 248, 0.1)", "rgba(63, 185, 80, 0.1)", "rgba(171, 125, 248, 0.1)", "rgba(210, 153, 34, 0.1)", "rgba(248, 81, 73, 0.1)"],
}
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def rgba(hex_colour: str, alpha: float) -> str:
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r}, {g}, {b}, {alpha})"


def classic_css(t: dict) -> str:
    for key in ["page", "ink", "inkStrong", "inkSoft", "link", "line", "lineFirm", "surface", "surfaceEdge", "code", "quote"]:
        assert HEX.match(t[key]), f"{t['id']}.{key}: {t[key]!r} is not #rrggbb"
    assert len(t["tokens"]) == len(TOKENS) and all(HEX.match(c) for c in t["tokens"]), f"{t['id']}: tokens"
    fonts = t.get("fonts", {})
    alerts = ALERTS[t["dark"]]
    lines = [
        f"/* {t['name']}: {t['description']}.",
        "   A classic theme in Tinta's design (github.com/oipoistar/tinta, MIT): Tinta's rules,",
        "   this theme's colours. Generated by scripts/import-page-themes.py from themes/classic.json. */",
        ":root {",
        f"  color-scheme: {'dark' if t['dark'] else 'light'};",
        f"  accent-color: {t['link']};",
        f"  --page: {t['page']};",
        f"  --ink: {t['ink']};",
        f"  --ink-strong: {t['inkStrong']};",
        f"  --ink-soft: {t['inkSoft']};",
        f"  --link: {t['link']};",
        f"  --line: {t['line']};",
        f"  --line-firm: {t['lineFirm']};",
        f"  --surface: {t['surface']};",
        f"  --surface-edge: {t['surfaceEdge']};",
        f"  --code: {t['code']};",
        f"  --quote: {t['quote']};",
        "}",
        "body {",
        "  background-color: var(--page);",
        "  color: var(--ink);",
        f"  font-family: {fonts.get('body', FONT)};",
        "}",
        "h1, h2, h3, h4, h5, h6 {",
        "  color: var(--ink-strong);",
        f"  font-family: {fonts.get('heading', HEADING_FONT)};",
        "}",
        "h1 { font-size: 34px; letter-spacing: -0.02em; }",
        "h2 { font-size: 25px; font-weight: 600; letter-spacing: -0.015em; }",
        "h3 { font-size: 20px; font-weight: 600; letter-spacing: -0.01em; }",
        "h4 { font-size: 17px; font-weight: 600; }",
        "h5 { font-size: 15px; font-weight: 600; }",
        "h6 { font-size: 13px; font-weight: 600; letter-spacing: 0.03em; }",
        "h1, h2 { border-bottom: 1px solid var(--line); padding-bottom: 10px; }",
        f"a {{ color: var(--link); text-decoration-color: {rgba(t['link'], 0.4)}; }}",
        f"code, pre {{ font-family: {fonts.get('code', CODE_FONT)}; }}",
        "code { border-radius: 5px; }",
        "pre {",
        "  background-color: var(--surface);",
        "  color: var(--code);",
        "  border: 1px solid var(--surface-edge);",
        "  border-radius: 10px;",
        "}",
        *[f".token.{name} {{ color: {colour}; }}" for name, colour in zip(TOKENS, t["tokens"])],
        "blockquote { border-left-color: var(--quote); color: var(--ink-soft); }",
        *[f"blockquote.alert-{kind} {{ background-color: {tint}; }}" for kind, tint in zip(["note", "tip", "important", "warning", "caution"], alerts)],
        "blockquote.alert-note, blockquote.alert-tip, blockquote.alert-important, blockquote.alert-warning, blockquote.alert-caution {",
        "  padding: 10px 18px 0;",
        "  color: var(--ink);",
        "}",
        "li::marker { color: var(--ink-soft); }",
        "tr { background-color: transparent; }",
        "th, td { border: none; border-bottom: 1px solid var(--line); padding: 9px 14px; }",
        "th { background-color: transparent; border-bottom: 2px solid var(--line-firm); }",
        "hr { border-top: 1px solid var(--line); }",
    ]
    if "mark" in t:
        lines.append(f"mark {{ background-color: {t['mark'][0]}; color: {t['mark'][1]}; }}")
    return "\n".join(lines) + "\n"


themes = []
for css_file in sorted((root / "themes" / "tinta").glob("*.css")):
    css = css_file.read_text(encoding="utf-8")
    head = re.match(r"/\*\s*([^:]+):\s*([^\n]*)", css)
    assert head, f"{css_file.name}: no '/* Name: description' header"
    dark = re.search(r"color-scheme:\s*dark", css) is not None
    description = head.group(2).strip().rstrip(".")
    themes.append({"id": css_file.stem, "name": head.group(1).strip(), "description": description, "dark": dark, "group": "Tinta", "css": css})

classic = json.loads((root / "themes" / "classic.json").read_text(encoding="utf-8"))["themes"]
for t in classic:
    themes.append({"id": t["id"], "name": t["name"], "description": t["description"], "dark": t["dark"], "group": "Classic", "css": classic_css(t)})

ids = [t["id"] for t in themes]
assert len(ids) == len(set(ids)), f"duplicate theme ids: {sorted(i for i in ids if ids.count(i) > 1)}"
assert len(themes) <= 64, "Orca refuses a picker with more than 64 values"

# Picker order: Paper first (the default), then Tinta light, Tinta dark, classic light, classic dark.
ordered = sorted(themes, key=lambda t: (t["id"] != "paper", t["group"] != "Tinta", t["dark"], t["name"].lower()))

lines = [
    "// Generated by scripts/import-page-themes.py: Tinta's built-in themes (github.com/oipoistar/tinta,",
    "// resources/themes, MIT) and classic themes in Tinta's design (themes/classic.json). Do not edit by hand.",
    "export interface PageTheme { id: string; name: string; description: string; dark: boolean; group: 'Tinta' | 'Classic'; css: string }",
    "export const pageThemes: PageTheme[] = [",
]
for t in ordered:
    fields = ", ".join(f"{k}: {json.dumps(t[k], ensure_ascii=False)}" for k in ["id", "name", "description", "dark", "group", "css"])
    lines.append(f"  {{ {fields} }},")
lines.append("]")
(root / "editor" / "page-themes.ts").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

manifest_path = root / "orca-plugin.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
setting = next(s for s in manifest["contributes"]["settings"] if s["key"] == "theme")
setting["enum"] = [t["id"] for t in ordered]
setting["enumLabels"] = [f"{t['name']} ({t['group']}, {'dark' if t['dark'] else 'light'})" for t in ordered]
setting["description"] = "Tinta's built-in themes and classic themes in Tinta's design. Also in the viewer's gear menu."
manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")

light = sum(not t["dark"] for t in themes)
print(f"editor/page-themes.ts: {len(themes)} themes ({len(themes) - len(classic)} Tinta, {len(classic)} classic; {light} light, {len(themes) - light} dark)")
