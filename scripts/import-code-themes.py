"""Regenerate editor/code-themes.ts and the codeTheme enum in orca-plugin.json from highlight.js styles.

Usage: python -I scripts/import-code-themes.py <styles-dir>
<styles-dir> is the `styles` folder of the @highlightjs/cdn-assets npm package
(`npm pack @highlightjs/cdn-assets@11`, then unpack it). It reads `*.min.css` and `base16/*.min.css`.
"""
import json
import pathlib
import re
import sys

# Shown first, in this order, under "Popular"; the rest of highlight.js follows, then base16.
POPULAR = [
    "github", "github-dark", "github-dark-dimmed", "atom-one-dark", "atom-one-light", "monokai",
    "monokai-sublime", "nord", "night-owl", "tokyo-night-dark", "tokyo-night-light", "vs2015", "vs",
    "xcode", "intellij-light", "androidstudio", "stackoverflow-dark", "stackoverflow-light",
    "rose-pine", "rose-pine-moon", "rose-pine-dawn", "panda-syntax-dark", "shades-of-purple",
    "base16/dracula", "base16/gruvbox-dark-medium", "base16/gruvbox-light-medium",
    "base16/solarized-dark", "base16/solarized-light", "base16/material", "base16/one-light",
]
# Kept out of the generated module (and so of the picker): the plugin's own options use these ids.
RESERVED = {"ayu-dark", "page"}

root = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) != 2:
    sys.exit(__doc__)
styles = pathlib.Path(sys.argv[1])


def label(css: str, theme_id: str) -> str:
    name = re.search(r"Theme:\s*([^\n*]+)", css)
    text = name.group(1).strip() if name else theme_id.split("/")[-1].replace("-", " ").title()
    return f"{text} (base16)" if theme_id.startswith("base16/") else text


def strip_layout(css: str) -> str:
    # The page lays out code blocks itself; keep only the themes' colours and font styles.
    return re.sub(r"pre code\.hljs\{[^}]*\}code\.hljs\{[^}]*\}", "", css, count=1)


found = {}
for path in sorted(styles.glob("*.min.css")) + sorted((styles / "base16").glob("*.min.css")):
    theme_id = path.relative_to(styles).as_posix().removesuffix(".min.css")
    if theme_id in RESERVED:
        continue
    css = path.read_text(encoding="utf-8")
    found[theme_id] = {"id": theme_id, "name": label(css, theme_id), "css": strip_layout(css)}

missing = [t for t in POPULAR if t not in found]
assert not missing, f"popular themes not in {styles}: {missing}"
assert len(found) > 100, f"only {len(found)} themes in {styles}; wrong folder?"

popular = [found[t] | {"group": "Popular"} for t in POPULAR]
rest = sorted((t for k, t in found.items() if k not in POPULAR), key=lambda t: (t["id"].startswith("base16/"), t["name"].lower()))
ordered = popular + [t | {"group": "Base16" if t["id"].startswith("base16/") else "More highlight.js"} for t in rest]

lines = [
    "// Generated by scripts/import-code-themes.py from highlight.js styles (BSD-3-Clause; base16",
    "// schemes MIT or more permissive). Do not edit by hand.",
    "export interface CodeTheme { id: string; name: string; group: string; css: string }",
    "export const codeThemes: CodeTheme[] = [",
]
for t in ordered:
    lines.append(f"  {{ id: {json.dumps(t['id'])}, name: {json.dumps(t['name'])}, group: {json.dumps(t['group'])}, css: {json.dumps(t['css'])} }},")
lines.append("]")
(root / "editor" / "code-themes.ts").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

# Orca caps a picker at 64 values, so Settings lists the plugin's two options and the popular ones;
# every other theme goes through the free-text codeThemeCustom setting (the viewer's menu fills it).
manifest_path = root / "orca-plugin.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
setting = next(s for s in manifest["contributes"]["settings"] if s["key"] == "codeTheme")
setting["enum"] = ["ayu-dark", "page"] + [t["id"] for t in popular]
setting["enumLabels"] = ["Ayu Dark", "Same as the page theme"] + [t["name"] for t in popular]
assert len(setting["enum"]) <= 64, "Orca refuses a picker with more than 64 values"
manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
print(f"editor/code-themes.ts: {len(ordered)} themes ({len(popular)} popular, in the Settings picker); orca-plugin.json updated")
