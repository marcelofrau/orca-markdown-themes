"""Regenerate editor/tinta-themes.ts from Tinta's built-in theme sheets.

Usage: python -I scripts/import-tinta-themes.py [themes-dir]
themes-dir defaults to themes/tinta (copies of github.com/oipoistar/tinta resources/themes/*.css).
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "themes" / "tinta"
out = root / "editor" / "tinta-themes.ts"

themes = []
for css_file in sorted(src.glob("*.css")):
    css = css_file.read_text(encoding="utf-8")
    head = re.match(r"/\*\s*([^:]+):\s*([^\n]*)", css)
    assert head, f"{css_file.name}: no '/* Name: description' header"
    dark = re.search(r"color-scheme:\s*dark", css) is not None
    themes.append({"id": css_file.stem, "name": head.group(1).strip(), "dark": dark, "css": css})

assert themes, f"no .css files in {src}"
lines = [
    "// Generated by scripts/import-tinta-themes.py from Tinta's built-in themes",
    "// (github.com/oipoistar/tinta, resources/themes, MIT). Do not edit by hand.",
    "export interface TintaTheme { id: string; name: string; dark: boolean; css: string }",
    "export const tintaThemes: TintaTheme[] = [",
]
for t in themes:
    lines.append(f"  {{ id: {json.dumps(t['id'])}, name: {json.dumps(t['name'])}, dark: {json.dumps(t['dark'])}, css: {json.dumps(t['css'])} }},")
lines.append("]")
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{out.relative_to(root)}: {len(themes)} themes ({', '.join(t['name'] for t in themes)})")
